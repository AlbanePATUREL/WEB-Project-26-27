-- On repart de zéro si la table existe déjà (pratique en dev)
drop table if exists public.gadgets;

create table public.gadgets (
  -- Identifiant auto-incrémenté (on ne le met pas dans le CSV)
  id          int8 generated by default as identity primary key,
  nom         text    not null,
  -- Un prix ne peut pas être négatif
  prix        numeric not null check (prix >= 0),
  -- Seules ces 5 catégories sont acceptées (même liste que dans l'API)
  categorie   text check (categorie in ('Communication', 'Attaque', 'Évasion', 'Infiltration', 'Beauté-Tech')),
  -- Clé du modèle 3D affiché par le front (ex : "compowder")
  visuel      text,
  -- Le seul booléen : le gadget est-il en stock ou "en mission" ?
  disponible  boolean not null default true
);

-- Row Level Security activée SANS aucune policy :
-- => la clé publique (anon / publishable) ne peut RIEN lire ni écrire.
-- => seul notre serveur Express, qui utilise la secret key, passe outre la RLS.
alter table public.gadgets enable row level security;
